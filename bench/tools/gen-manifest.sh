#!/usr/bin/env bash
#
# drain-bench - generate the standalone dataset manifest from the labeled corpus.
#
# Reads every fixtures/<vector>/<tier>/<target>/meta (the frozen wal v0.1 label manifest)
# and emits a single machine-readable TSV describing the dataset, decoupled from the wal
# harness internals. This is the "standalone dataset" view: a consumer scores any tool
# against these labels with bench/score.sh, without needing the wal Foundry suite.
#
# Columns (tab-separated): vector  tier  target  label  split  test  source_dir  provenance
#   - split: honesty marker. Every current fixture is `dev` (non-independent: the wal
#     detectors were tuned against these cases). A genuine `holdout` row may only be a NEW
#     fixture authored without tuning wal to it (detectors frozen at v0.1). The generator
#     reads an optional `split=` key from meta; absent ⇒ `dev`.
#   - provenance is free text and always last (it may contain spaces, never tabs).
#
# Usage:  bench/tools/gen-manifest.sh [> bench/dataset/manifest.tsv]
#   Writes to stdout. The repo root is derived from this script's location.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
FIXTURES="$REPO_ROOT/fixtures"

if [ ! -d "$FIXTURES" ] || [ -z "$(find "$FIXTURES" -name meta 2>/dev/null)" ]; then
  echo "error: no labeled fixtures found under $FIXTURES/**/meta" >&2
  exit 1
fi

printf '# drain-bench dataset manifest - generated by bench/tools/gen-manifest.sh, do not edit by hand\n'
printf '# columns: vector\\ttier\\ttarget\\tlabel\\tsplit\\ttest\\tsource_dir\\tprovenance\n'
printf 'vector\ttier\ttarget\tlabel\tsplit\ttest\tsource_dir\tprovenance\n'

n=0
while IFS= read -r meta; do
  vector=""; tier=""; target=""; label=""; split=""; test=""; provenance=""
  while IFS='=' read -r k v; do
    # meta is strict key=value; strip leading/trailing whitespace around key and value so a
    # stray space (e.g. "label= safe") does not abort or leak into the TSV column.
    k="${k#"${k%%[![:space:]]*}"}"; k="${k%"${k##*[![:space:]]}"}"
    v="${v#"${v%%[![:space:]]*}"}"; v="${v%"${v##*[![:space:]]}"}"
    case "$k" in
      vector)     vector="$v" ;;
      tier)       tier="$v" ;;
      target)     target="$v" ;;
      label)      label="$v" ;;
      split)      split="$v" ;;
      test)       test="$v" ;;
      provenance) provenance="$v" ;;
    esac
  done < <(grep -vE '^\s*#' "$meta")

  if [ -z "$vector" ] || [ -z "$tier" ] || [ -z "$target" ] || [ -z "$label" ]; then
    echo "error: $meta missing required key (vector/tier/target/label)" >&2; exit 1
  fi
  if [ "$label" != "vuln" ] && [ "$label" != "safe" ]; then
    echo "error: $meta invalid label '$label' (expected vuln|safe)" >&2; exit 1
  fi
  # honesty default: all current corpus fixtures are non-independent -> dev
  [ -z "$split" ] && split="dev"
  if [ "$split" != "dev" ] && [ "$split" != "holdout" ]; then
    echo "error: $meta invalid split '$split' (expected dev|holdout)" >&2; exit 1
  fi
  [ -z "$test" ] && test="-"
  [ -z "$provenance" ] && provenance="-"

  source_dir="${meta%/meta}"
  source_dir="${source_dir#"$REPO_ROOT"/}"

  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$vector" "$tier" "$target" "$label" "$split" "$test" "$source_dir" "$provenance"
  n=$((n+1))
done < <(find "$FIXTURES" -name meta | sort)

echo "# $n fixtures" >&2
