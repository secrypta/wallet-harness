#!/usr/bin/env bash
#
# drain-bench - wal adapter: run the wal Foundry suite in Docker and write its verdicts in
# the drain-bench verdict format, so they can be scored with bench/score.sh like any tool.
#
#   [<vector>] target=<target> verdict=<VULNERABLE|BLOCKED>
#
# This is the ONLY wal-specific step. Scoring itself (bench/score.sh) is tool-agnostic.
# Mirrors harness/benchmark.sh's Docker invocation (same image / mem / container cap).
#
# Usage:  bench/tools/run-wal.sh [-o <out-file>]
#   default out: bench/results/wal/verdicts.txt
# Requires: Docker + ghcr.io/foundry-rs/foundry; forge-std in lib/ (see ../README.md).

set -euo pipefail

IMAGE="ghcr.io/foundry-rs/foundry:stable"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAX_CONTAINERS=3
MEM_LIMIT="2g"
OUT="$REPO_ROOT/bench/results/wal/verdicts.txt"

while [ $# -gt 0 ]; do
  case "$1" in
    -o) OUT="$2"; shift 2 ;;
    -h|--help) grep -E '^#' "$0" | sed -E 's/^# ?//'; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

cd "$REPO_ROOT"

# --- preflight ---
if [ ! -f lib/forge-std/src/Test.sol ]; then
  echo "error: lib/forge-std not found. See ../README.md (clone the pinned forge-std into lib/)." >&2
  exit 1
fi
running="$(docker ps -q | wc -l | tr -d ' ')"
if [ "$running" -ge "$MAX_CONTAINERS" ]; then
  echo "error: $running containers already running (cap $MAX_CONTAINERS). Free one first." >&2
  exit 1
fi

echo "== drain-bench: running wal harness in Docker ($IMAGE, mem=$MEM_LIMIT) =="
raw="$(mktemp)"; trap 'rm -f "$raw"' EXIT
docker run --rm \
  --cpus=4 --memory="$MEM_LIMIT" --memory-swap="$MEM_LIMIT" --pids-limit=1024 \
  -e HOME=/tmp \
  -v "$REPO_ROOT":/src:ro \
  --entrypoint sh \
  "$IMAGE" \
  -c 'cp -r /src /tmp/work && cd /tmp/work && forge test -vv' > "$raw" 2>&1 || {
    echo "error: forge suite failed to run:" >&2; tail -20 "$raw" >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
{
  echo "# wal harness verdicts - generated by bench/tools/run-wal.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  echo "# image=$IMAGE  wal tag=$(git -C "$REPO_ROOT" describe --tags --always 2>/dev/null || echo unknown)"
  grep -oE '\[[a-z0-9-]+\] target=[a-z0-9-]+ verdict=(VULNERABLE|BLOCKED)' "$raw" | sort -u
} > "$OUT"

n="$(grep -cE '^\[' "$OUT" || true)"
echo "wrote $n verdict lines -> $OUT"
echo "score it:  bench/score.sh $OUT --strict"
